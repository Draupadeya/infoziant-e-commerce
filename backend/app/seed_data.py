def seed_database(db):
    try:
        # Check if simulation_type column exists, if not add it
        try:
            db.execute(text("ALTER TABLE products ADD COLUMN simulation_type VARCHAR(50) DEFAULT 'wallet'"))
            db.commit()
        except Exception:
            db.rollback()

        for p in SEED_PRODUCTS:
            existing = db.query(Product).filter(Product.slug == p["slug"]).first()
            if existing:
                for k, v in p.items():
                    setattr(existing, k, v)
            else:
                db_product = Product(**p)
                db.add(db_product)
        db.commit()
    except Exception as e:
        db.rollback()
        print(f"Error seeding database: {e}")

if __name__ == "__main__":
    from .database import SessionLocal
    db = SessionLocal()
    seed_database(db)
    count = db.query(Product).count()
    print(f"Successfully seeded database! Total products now: {count}")
    db.close()

